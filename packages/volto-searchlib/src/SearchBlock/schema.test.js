import registry from '@eeacms/search/registry';
import { SearchBlockSchema } from './schema';
import { applyBlockSettings } from './utils';

describe('SearchBlockSchema', () => {
  it('defines AI summary copy defaults in the registry', () => {
    const defaults = registry.searchui.default.chatbotAnswer;
    expect(defaults.continueConversationLabel).toBe('Continue conversation');
    expect(defaults.aiDisclaimer).toMatch(
      /This response was generated by artificial intelligence/,
    );
    expect(defaults.aiSummaryDisabledDescription).toMatch(
      /AI summaries are turned off/,
    );
  });

  it.each(
    [
      'continueConversationLabel',
      'aiDisclaimer',
      'aiSummaryDisabledDescription',
    ].flatMap((field) =>
      [undefined, null, '', 'Custom block text'].map((value) => [field, value]),
    ),
  )(
    'preserves configured defaults for empty %s overrides (%s)',
    (field, value) => {
      const schema = SearchBlockSchema({});
      const appName = `${field}-${value}`;
      const configuredDefault = `Configured default for ${field}`;
      const config = {
        searchui: {
          [appName]: { chatbotAnswer: { [field]: configuredDefault } },
        },
      };
      const result = applyBlockSettings(
        config,
        appName,
        { [field]: value },
        schema,
      );
      expect(result.searchui[appName].chatbotAnswer[field]).toBe(
        value || configuredDefault,
      );
      expect(config.searchui[appName].chatbotAnswer[field]).toBe(
        configuredDefault,
      );
    },
  );

  it('should return default schema without formData', () => {
    const schema = SearchBlockSchema({});
    expect(schema.title).toBe('Searchlib Block');
    expect(schema.required).toEqual(['appName']);
  });

  it('exposes the disabled summary description and maps it into the chatbot config', () => {
    const schema = SearchBlockSchema({
      formData: { enableChatbotAnswer: true },
      assistants: [{ id: 1, name: 'Search Assist' }],
    });
    expect(
      schema.fieldsets.find(({ id }) => id === 'assistants').fields,
    ).toContain('aiSummaryDisabledDescription');
    expect(schema.properties.aiSummaryDisabledDescription.widget).toBe(
      'textarea',
    );

    const registry = applyBlockSettings(
      { searchui: { default: { chatbotAnswer: {} } } },
      'default',
      { aiSummaryDisabledDescription: 'Enable summaries for an AI overview.' },
      schema,
    );
    expect(
      registry.searchui.default.chatbotAnswer.aiSummaryDisabledDescription,
    ).toBe('Enable summaries for an AI overview.');
  });

  it('should modify the config with valid JSON', () => {
    const schema = SearchBlockSchema({});
    const modifyConfig = schema.properties.customConfig.modifyConfig;
    const config = { existingKey: 'existingValue' };
    const data = '{"newKey": "newValue"}';

    modifyConfig(config, data);

    expect(config).toEqual({
      existingKey: 'existingValue',
      newKey: 'newValue',
    });
  });

  it('should not modify the config with invalid JSON', () => {
    const schema = SearchBlockSchema({});
    const modifyConfig = schema.properties.customConfig.modifyConfig;
    const config = { existingKey: 'existingValue' };
    const data = 'invalid JSON';

    modifyConfig(config, data);

    expect(config).toEqual({
      existingKey: 'existingValue',
    });
  });

  it('should overwrite existing keys in the config', () => {
    const schema = SearchBlockSchema({});
    const modifyConfig = schema.properties.customConfig.modifyConfig;
    const config = { keyToOverwrite: 'oldValue' };
    const data = '{"keyToOverwrite": "newValue"}';

    modifyConfig(config, data);

    expect(config).toEqual({
      keyToOverwrite: 'newValue',
    });
  });
});
